export function isB2bLocation(): boolean {
  if (typeof window === 'undefined') return false;
  const hostname = window.location.hostname.toLowerCase();
  const port = window.location.port;
  const pathname = window.location.pathname.toLowerCase();
  const params = new URLSearchParams(window.location.search);
  const siteParam = params.get('site')?.toLowerCase();

  if (siteParam === 'b2b') return true;
  if (siteParam === 'b2c') return false;
  if (hostname.startsWith('b2b.') || port === '3001') return true;
  if (pathname === '/b2b' || pathname.startsWith('/b2b/')) return true;

  const b2bPrefixes = [
    '/marketplace',
    '/suppliers',
    '/rfq',
    '/leads',
    '/feed',
    '/onboarding',
    '/affiliates',
    '/seller',
    '/apply-seller',
    '/company/',
    '/wholesale/',
    '/join',
  ];
  return b2bPrefixes.some((p) => pathname === p || pathname.startsWith(p));
}

export function resolveLanguageForMode(mode: 'b2b' | 'b2c'): 'sv' | 'en' {
  if (typeof window === 'undefined') return mode === 'b2b' ? 'en' : 'sv';
  try {
    const params = new URLSearchParams(window.location.search);
    const urlLang = params.get('lang')?.toLowerCase();
    if (urlLang === 'en' || urlLang === 'sv') {
      return urlLang;
    }
    const modeKey = mode === 'b2b' ? 'hatake_lang_b2b' : 'hatake_lang_b2c';
    const saved = localStorage.getItem(modeKey)?.toLowerCase();
    if (saved === 'en' || saved === 'sv') {
      return saved;
    }
  } catch {}
  // Default: English ('en') on B2B site, Swedish ('sv') on B2C site
  return mode === 'b2b' ? 'en' : 'sv';
}

function resolveInitialLanguage(): 'sv' | 'en' {
  return resolveLanguageForMode(isB2bLocation() ? 'b2b' : 'b2c');
}

